// Posición "libre" (valor heredado en la app) se trata como central.
const ALIASES = { libre: "central" };

export function resolvePositionKey(position) {
  const k = ALIASES[position] || position;
  return POSITION_CATALOG[k] ? k : null;
}

export function getPositionCatalog(position) {
  const k = resolvePositionKey(position);
  return k ? { key: k, ...POSITION_CATALOG[k] } : null;
}

export function getRoleOptions(position) {
  const c = getPositionCatalog(position);
  return c ? c.roles.map((r) => ({ value: r.id, label: r.label })) : [];
}

export function findRole(roleId) {
  for (const [pk, pos] of Object.entries(POSITION_CATALOG)) {
    const role = pos.roles.find((r) => r.id === roleId);
    if (role) return { positionKey: pk, position: pos, role };
  }
  return null;
}

// Competencias seleccionables en el PDI: generales de la posición + específicas del rol.
export function getSelectableCompetencies(position, roleId) {
  const c = getPositionCatalog(position);
  if (!c) return { general: [], role: [] };
  const general = [];
  Object.entries(c.groups).forEach(([group, items]) => {
    items.forEach((text, i) => general.push({ id: `${c.key}.${group}.${i}`, source: "general", group, text }));
  });
  const role = [];
  const r = c.roles.find((x) => x.id === roleId);
  if (r) r.key.forEach((text, i) => role.push({ id: `${r.id}.key.${i}`, source: "role", group: "rol", text, roleLabel: r.label }));
  return { general, role };
}
